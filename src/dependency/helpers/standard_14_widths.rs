#[cfg(test)]
mod tests {
    use super::{standard_14_font_width, supports_standard_14_font};

    #[test]
    fn supports_corpus_standard_fonts() {
        assert!(supports_standard_14_font("Helvetica"));
        assert!(supports_standard_14_font("Helvetica-Bold"));
        assert!(supports_standard_14_font("Times-Roman"));
        assert!(supports_standard_14_font("Courier"));
        assert!(!supports_standard_14_font("Arial"));
    }

    #[test]
    fn returns_expected_extra_glyph_widths() {
        assert_eq!(standard_14_font_width("Helvetica-Bold", 'ó'), Some(611_i32));
        assert_eq!(standard_14_font_width("Courier", '–'), Some(600_i32));
        assert_eq!(standard_14_font_width("Times-Roman", '’'), Some(333_i32));
    }
}
