#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Standard14FontKind {
    Courier,
    Helvetica,
    HelveticaBold,
    TimesRoman,
}

#[inline]
pub(crate) fn supports_standard_14_font(base_font: &str) -> bool {
    standard_14_font_kind(base_font).is_some()
}

#[inline]
pub(crate) fn standard_14_font_width(base_font: &str, ch: char) -> Option<i32> {
    match standard_14_font_kind(base_font)? {
        Standard14FontKind::Courier => courier_width(ch),
        Standard14FontKind::Helvetica => helvetica_width(ch),
        Standard14FontKind::HelveticaBold => helvetica_bold_width(ch),
        Standard14FontKind::TimesRoman => times_roman_width(ch),
    }
}

fn standard_14_font_kind(base_font: &str) -> Option<Standard14FontKind> {
    match base_font {
        "Courier" => Some(Standard14FontKind::Courier),
        "Helvetica" => Some(Standard14FontKind::Helvetica),
        "Helvetica-Bold" => Some(Standard14FontKind::HelveticaBold),
        "Times-Roman" => Some(Standard14FontKind::TimesRoman),
        _ => None,
    }
}

fn courier_width(ch: char) -> Option<i32> {
    if ch.is_control() {
        return None;
    }
    Some(600)
}

